import { afterEach, describe, expect, test } from 'vitest'
import { chmodSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { VERSION } from '../../src/cli/context.js'
import { COMMANDS, PLUMBING } from '../../src/cli/registry.js'
import { exec } from '../../src/core/runtime/exec.js'
import {
  MANIFEST,
  WRAPPER_FILES,
  generatedFiles,
  renderWrapper,
  staleGeneratedFiles,
  wrapperPath,
  writeGeneratedFiles,
} from '../../src/generate/index.js'
import { accounts } from '../harness/index.js'
import { createCiScene } from '../internal/ci/ci-fixture.js'

/** @type {string[]} */
const dirs = []
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true })
})

function scratch() {
  const dir = mkdtempSync(join(tmpdir(), 'hackwin-wrappers-'))
  dirs.push(dir)
  return dir
}

/**
 * The command line of a wrapper: the one line of its `sh` code block.
 * @param {string} content
 */
function commandLineOf(content) {
  const match = /^```sh\n(.*)\n```$/m.exec(content)
  if (!match) throw new Error(`no command line in:\n${content}`)
  return match[1]
}

/** What the session types after `/<command>` in the runs below. */
const ARGUMENTS = /** @type {Record<string, string>} */ ({
  setup: '--answers answers.yml',
  join: '--answers answers.yml',
  take: '42',
  ship: '',
  status: '',
  gate: '',
})

describe('AC67/wrappers: wrappers only for the commands of the registry', () => {
  test('one wrapper per command of the registry, none for the plumbing namespace', () => {
    expect(WRAPPER_FILES.map(({ path }) => path)).toEqual(
      COMMANDS.map(({ name }) => `.claude/skills/${name}/SKILL.md`),
    )
    expect(COMMANDS.map(({ name }) => name)).toEqual([
      'setup',
      'join',
      'take',
      'ship',
      'status',
      'gate',
    ])
    const claude = MANIFEST.filter(({ path }) => path.startsWith('.claude/'))
    expect(claude.map(({ path }) => path)).toEqual(WRAPPER_FILES.map(({ path }) => path))
    for (const { name } of PLUMBING) {
      expect(claude.some(({ path }) => path.includes(name.split(' ').at(-1) ?? name))).toBe(false)
    }
  })

  test('the files written into a checkout are exactly those wrappers', async () => {
    const root = scratch()
    const written = await writeGeneratedFiles(root, { version: VERSION })
    expect(
      written.filter(({ path }) => path.startsWith('.claude/')).map(({ path }) => path),
    ).toEqual(COMMANDS.map(({ name }) => wrapperPath(name)))
  })
})

describe('1.4c/wrappers: each wrapper only calls its command with HACKWIN_CALLER=claude-code', () => {
  test('each wrapper names the version, is a skill that only the human starts, and allows only its command line', () => {
    for (const entry of COMMANDS) {
      const content = renderWrapper(entry, { version: VERSION })
      const lines = content.split('\n')
      expect(lines.slice(0, 3)).toEqual([
        '---',
        `# Generated by hackwin ${VERSION}. Do not edit: hackwin setup --regenerate rewrites this file.`,
        `name: ${entry.name}`,
      ])
      expect(lines).toContain('disable-model-invocation: true')
      expect(lines).toContain(
        `allowed-tools: "Bash(HACKWIN_CALLER=claude-code hackwin ${entry.name}), Bash(HACKWIN_CALLER=claude-code hackwin ${entry.name} *)"`,
      )
      expect(commandLineOf(content)).toBe(
        `HACKWIN_CALLER=claude-code hackwin ${entry.name} $ARGUMENTS`,
      )
      expect(content).toContain('do not change the directory')
      expect(content).not.toMatch(/[ \t]$/m)
    }
    const take = renderWrapper(COMMANDS[2], { version: VERSION })
    expect(take).toContain('argument-hint: "[N] [--release]"')
  })

  test("each wrapper's command line runs hackwin <command> with the arguments, and passes on its output and exit code", async () => {
    const dir = scratch()
    const log = join(dir, 'calls.log')
    writeFileSync(
      join(dir, 'hackwin'),
      [
        '#!/bin/sh',
        `printf 'caller=%s args=%s\\n' "$HACKWIN_CALLER" "$*" >> ${JSON.stringify(log)}`,
        'echo "hackwin $1: the output of the command"',
        'echo "hackwin $1: a warning" >&2',
        'exit 1',
        '',
      ].join('\n'),
    )
    chmodSync(join(dir, 'hackwin'), 0o755)
    const env = { ...process.env, PATH: `${dir}:${process.env.PATH}`, HACKWIN_CALLER: undefined }

    for (const { path, content } of generatedFiles({ version: VERSION })) {
      if (!path.startsWith('.claude/')) continue
      const command = path.split('/')[2]
      const line = commandLineOf(content).replace('$ARGUMENTS', ARGUMENTS[command])
      const result = await exec('/bin/sh', ['-c', line], { cwd: dir, env })
      expect(result.code, path).toBe(1)
      expect(result.stdout, path).toBe(`hackwin ${command}: the output of the command\n`)
      expect(result.stderr, path).toBe(`hackwin ${command}: a warning\n`)
    }
    expect(readFileSync(log, 'utf8').trimEnd().split('\n')).toEqual(
      COMMANDS.map(({ name }) => `caller=claude-code args=${name} ${ARGUMENTS[name]}`.trimEnd()),
    )
  })

  test('a wrapper edited by hand, or from another version, is stale', async () => {
    const root = scratch()
    await writeGeneratedFiles(root, { version: VERSION })
    const take = join(root, wrapperPath('take'))
    writeFileSync(take, readFileSync(take, 'utf8').replace('do not change the directory', 'cd'))
    writeFileSync(join(root, wrapperPath('gate')), renderWrapper(COMMANDS[5], { version: '9.9.9' }))

    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([
      { path: '.claude/skills/take/SKILL.md', problem: 'changed' },
      { path: '.claude/skills/gate/SKILL.md', problem: 'changed' },
    ])
  })
})

describe('AC71/wrapper: a hand-edited wrapper fails CI (E19)', () => {
  test("a pull request of the Lead that changes a generated wrapper by hand fails CI's generated file step", async () => {
    const scene = await createCiScene()
    const branch = 'task/20-shared-change'
    const clone = await scene.fixture.clone('lead')
    await clone.git.run(['checkout', '--quiet', '-b', branch, 'origin/main'])
    const path = wrapperPath('take')
    const wrapper = readFileSync(join(clone.path, path), 'utf8')
    await scene.fixture.commit('Let /take move the session', {
      dir: clone.path,
      files: {
        [path]: wrapper.replace('do not change the directory', 'then cd into the worktree'),
      },
    })
    await clone.git.push({ refspecs: [`HEAD:refs/heads/${branch}`] })
    const head = await clone.git.revParse('HEAD')

    const result = await scene.runCi({ branch, head, author: accounts.lead.login })

    expect(result.code).toBe(1)
    expect(result.json.error).toMatchObject({
      kind: 'blocked',
      message: `step 6, generated files: 1 generated file of the branch differs from the output of hackwin ${VERSION}`,
      rule: 'E19: generated wrappers and hook shims are not edited by hand',
      objects: [`${path}: its content differs from what hackwin ${VERSION} generates`],
    })
  })
})
