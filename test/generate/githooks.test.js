import { afterEach, describe, expect, test } from 'vitest'
import { chmodSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { VERSION } from '../../src/cli/context.js'
import { HOOKS_PATH } from '../../src/core/worktrees/index.js'
import {
  GIT_HOOKS,
  MANIFEST,
  generatedFiles,
  renderShim,
  staleGeneratedFiles,
  writeGeneratedFiles,
} from '../../src/generate/index.js'

/** @type {string[]} */
const dirs = []
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true })
})

function scratch() {
  const dir = mkdtempSync(join(tmpdir(), 'hackwin-generate-'))
  dirs.push(dir)
  return dir
}

describe('1.4a/shims: the git hook shims', () => {
  test('each shim names the running version in its header and is a single call to hackwin internal hook <name>', () => {
    expect(GIT_HOOKS).toEqual(['pre-commit', 'pre-push'])
    for (const hook of GIT_HOOKS) {
      const lines = renderShim(hook, { version: VERSION }).split('\n')
      expect(lines[0]).toBe('#!/bin/sh')
      expect(lines[1]).toBe(
        `# Generated by hackwin ${VERSION}. Do not edit: hackwin setup --regenerate rewrites this file.`,
      )
      const commands = lines.filter((line) => line !== '' && !line.startsWith('#'))
      expect(commands).toEqual([
        hook === 'pre-push'
          ? 'exec hackwin internal hook pre-push "$@"'
          : 'exec hackwin internal hook pre-commit',
      ])
    }
  })

  test('the generated file manifest registers both shims as executable files under .githooks', () => {
    const shims = MANIFEST.filter((entry) => entry.path.startsWith(`${HOOKS_PATH}/`))
    expect(shims.map(({ path, mode }) => ({ path, mode }))).toEqual([
      { path: '.githooks/pre-commit', mode: 0o755 },
      { path: '.githooks/pre-push', mode: 0o755 },
    ])
    const files = generatedFiles({ version: VERSION })
    expect(files.find((file) => file.path === '.githooks/pre-push')?.content).toBe(
      renderShim('pre-push', { version: VERSION }),
    )
  })

  test('the shims written into a checkout equal the generator output of the running version', async () => {
    const root = scratch()
    const written = await writeGeneratedFiles(root, { version: VERSION })
    expect(written.map((file) => file.path)).toEqual(MANIFEST.map((entry) => entry.path))
    for (const hook of GIT_HOOKS) {
      const file = join(root, HOOKS_PATH, hook)
      expect(readFileSync(file, 'utf8')).toBe(renderShim(hook, { version: VERSION }))
      expect(statSync(file).mode & 0o111).not.toBe(0)
    }
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([])
  })

  test('a hand edit, a missing shim, a lost executable bit and the output of another version are stale', async () => {
    const root = scratch()
    await writeGeneratedFiles(root, { version: VERSION })
    const preCommit = join(root, '.githooks/pre-commit')
    writeFileSync(preCommit, `${readFileSync(preCommit, 'utf8')}exit 0\n`)
    rmSync(join(root, '.githooks/pre-push'))
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([
      { path: '.githooks/pre-commit', problem: 'changed' },
      { path: '.githooks/pre-push', problem: 'missing' },
    ])

    await writeGeneratedFiles(root, { version: VERSION })
    chmodSync(join(root, '.githooks/pre-push'), 0o644)
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([
      { path: '.githooks/pre-push', problem: 'mode' },
    ])

    await writeGeneratedFiles(root, { version: '0.1.1' })
    const stale = await staleGeneratedFiles(root, { version: VERSION })
    expect(stale.filter((file) => file.path.startsWith(`${HOOKS_PATH}/`))).toEqual([
      { path: '.githooks/pre-commit', problem: 'changed' },
      { path: '.githooks/pre-push', problem: 'changed' },
    ])
  })
})
