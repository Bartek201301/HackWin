import { afterEach, describe, expect, test } from 'vitest'
import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parse } from 'yaml'
import { REPOSITORY_URL, VERSION } from '../../src/cli/context.js'
import { installCommand } from '../../src/core/config/index.js'
import {
  CI_EVENTS,
  CI_JOB,
  MANIFEST,
  WORKFLOW_PATH,
  generatedFiles,
  renderWorkflow,
  staleGeneratedFiles,
  writeGeneratedFiles,
} from '../../src/generate/index.js'
import { createFixture } from '../harness/index.js'
import { runInstallStep } from './install-step.js'

/** @type {string[]} */
const dirs = []
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true })
})

function scratch() {
  const dir = mkdtempSync(join(tmpdir(), 'hackwin-generate-'))
  dirs.push(dir)
  return dir
}

/**
 * The npm arguments of the install command of a version (contracts 6.3).
 * @param {string} version
 */
const npmArgs = (version) => installCommand(version, REPOSITORY_URL).replace(/^npm /, '')

describe('1.4b/workflow: the generated CI workflow', () => {
  test('the generated workflow equals the generator output of the running version', async () => {
    const entry = MANIFEST.find((file) => file.path === WORKFLOW_PATH)
    expect(entry).toMatchObject({ path: '.github/workflows/hackwin.yml', mode: 0o644 })
    const file = generatedFiles({ version: VERSION }).find((item) => item.path === WORKFLOW_PATH)
    expect(file?.content).toBe(renderWorkflow({ version: VERSION }))

    const root = scratch()
    await writeGeneratedFiles(root, { version: VERSION })
    const written = join(root, WORKFLOW_PATH)
    expect(readFileSync(written, 'utf8')).toBe(renderWorkflow({ version: VERSION }))
    expect(statSync(written).mode & 0o111).toBe(0)
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([])

    // A hand edit and the output of another version are stale.
    writeFileSync(written, `${renderWorkflow({ version: VERSION })}# edited\n`)
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([
      { path: WORKFLOW_PATH, problem: 'changed' },
    ])
    writeFileSync(written, renderWorkflow({ version: '0.1.0-0' }))
    expect(await staleGeneratedFiles(root, { version: VERSION })).toEqual([
      { path: WORKFLOW_PATH, problem: 'changed' },
    ])
  })

  test('its header names the CLI version that generated it', () => {
    const [first] = renderWorkflow({ version: VERSION }).split('\n')
    expect(first).toBe(
      `# Generated by hackwin ${VERSION}. Do not edit: hackwin setup --regenerate rewrites this file.`,
    )
    expect(renderWorkflow({ version: '0.1.1-pre.1' })).not.toBe(
      renderWorkflow({ version: VERSION }),
    )
  })

  test('one job named hackwin runs on every pull request event that opens a pull request or changes its head', () => {
    const workflow = parse(renderWorkflow({ version: VERSION }))
    expect(workflow.on).toEqual({ pull_request: { types: ['opened', 'reopened', 'synchronize'] } })
    expect(CI_EVENTS).toEqual(['opened', 'reopened', 'synchronize'])
    expect(Object.keys(workflow.jobs)).toEqual([CI_JOB])
    expect(CI_JOB).toBe('hackwin')
    // Without a name of its own, the job's check is named after it: `hackwin`.
    expect(workflow.jobs.hackwin.name).toBeUndefined()
    expect(workflow.permissions).toEqual({
      contents: 'read',
      issues: 'read',
      'pull-requests': 'read',
    })
  })

  test('the job checks out the head commit with its history, installs the CLI and runs hackwin internal ci', () => {
    const steps = parse(renderWorkflow({ version: VERSION })).jobs.hackwin.steps
    expect(steps.map((/** @type {any} */ step) => step.name)).toEqual([
      'Check out the head commit of the pull request',
      'Set up Node.js',
      'Install the hackwin CLI',
      'Run the hackwin checks',
    ])
    expect(steps[0].with).toEqual({
      ref: '${{ github.event.pull_request.head.sha }}',
      'fetch-depth': 0,
    })
    expect(steps[1].with).toEqual({ 'node-version': 22 })
    expect(steps[2]).toMatchObject({
      shell: 'bash',
      env: { BASE_REF: '${{ github.event.pull_request.base.ref }}' },
    })
    expect(steps[3]).toEqual({
      name: 'Run the hackwin checks',
      env: { GH_TOKEN: '${{ github.token }}' },
      run: 'hackwin internal ci',
    })
  })
})

describe('1.4b/workflow: which version the install step installs', () => {
  /**
   * A repository whose main pins `base` and a pull request branch that sets `head`, then the
   * install step run on the head commit.
   * @param {object} options
   * @param {string} options.base The hackwin.yml on main.
   * @param {string} [options.head] The hackwin.yml on the branch; main's by default.
   * @param {string} [options.mainLater] The hackwin.yml that main gets after the branch started.
   */
  async function install({ base, head, mainLater }) {
    const fixture = await createFixture({ files: { 'hackwin.yml': base } })
    const sha = await fixture.publish(
      head === undefined ? { 'notes.md': 'work\n' } : { 'hackwin.yml': head },
      {
        branch: 'task/20-install',
      },
    )
    if (mainLater !== undefined) await fixture.publish({ 'hackwin.yml': mainLater })
    const ci = await fixture.clone('ci')
    await ci.git.run(['checkout', '--quiet', '--detach', sha])
    return runInstallStep({
      version: VERSION,
      cwd: ci.path,
      dir: join(fixture.dir, 'install'),
      env: fixture.env,
    })
  }

  test('without a change of cli_version it installs the version pinned on the base branch, a pre-release by the URL of its .tgz', async () => {
    const result = await install({ base: 'schema: 1\ncli_version: 0.1.0-pre.3\n' })
    expect(result.code).toBe(0)
    expect(result.npm).toEqual([npmArgs('0.1.0-pre.3')])
    expect(result.npm[0]).toBe(
      'install -g https://github.com/Bartek201301/HackWin/releases/download/v0.1.0-pre.3/hackwin-0.1.0-pre.3.tgz',
    )
    expect(result.stdout).toContain('hackwin.yml on main pins 0.1.0-pre.3')
  })

  test('a pull request that raises cli_version to a patch of the same phase gets the version it names', async () => {
    const result = await install({
      base: 'cli_version: 0.1.0-pre.3\n',
      head: 'cli_version: "0.1.1-pre.1"  # bug fix release\n',
    })
    expect(result.code).toBe(0)
    expect(result.npm).toEqual([npmArgs('0.1.1-pre.1')])
    expect(result.stdout).toContain('this pull request sets cli_version to 0.1.1-pre.1')
  })

  test('a pull request that sets a version of another phase gets the version of the base branch', async () => {
    const result = await install({
      base: 'cli_version: 0.1.0-pre.3\n',
      head: "cli_version: '0.2.0-pre.1'\n",
    })
    expect(result.code).toBe(0)
    expect(result.npm).toEqual([npmArgs('0.1.0-pre.3')])
  })

  test('a newer version on the base branch is not the change of a pull request that started before it', async () => {
    const result = await install({
      base: 'cli_version: 0.1.0-pre.3\n',
      mainLater: 'cli_version: 0.1.1-pre.1\n',
    })
    expect(result.code).toBe(0)
    expect(result.npm).toEqual([npmArgs('0.1.1-pre.1')])
  })

  test('a release without a pre-release identifier is installed from npm', async () => {
    const result = await install({ base: 'cli_version: 0.1.0\n', head: 'cli_version: 0.1.1\n' })
    expect(result.code).toBe(0)
    expect(result.npm).toEqual(['install -g hackwin@0.1.1'])
    expect(result.npm).toEqual([npmArgs('0.1.1')])
  })

  test('a base branch without a pinned version stops the job before anything is installed', async () => {
    const result = await install({ base: 'schema: 1\n' })
    expect(result.code).not.toBe(0)
    expect(result.stderr).toContain('hackwin.yml on main pins no cli_version')
    expect(result.npm).toEqual([])
  })
})
